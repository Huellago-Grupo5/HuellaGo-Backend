-- Seguimiento cuantitativo y auditable de retos. Migración aditiva: conserva estado,
-- progreso porcentual, fechas, puntos, participaciones y resultados colectivos.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '60s';

ALTER TABLE public.retos
    ADD COLUMN IF NOT EXISTS meta_cantidad numeric(12,3),
    ADD COLUMN IF NOT EXISTS unidad_medida varchar(60);

-- La única información histórica disponible es el porcentaje. Se conserva como
-- cantidad base expresada en puntos porcentuales, sin crear eventos históricos.
UPDATE public.retos
SET meta_cantidad = COALESCE(meta_cantidad, 100),
    unidad_medida = COALESCE(NULLIF(btrim(unidad_medida), ''), 'puntos porcentuales');

ALTER TABLE public.retos ALTER COLUMN meta_cantidad SET DEFAULT 100;
ALTER TABLE public.retos ALTER COLUMN meta_cantidad SET NOT NULL;
ALTER TABLE public.retos ALTER COLUMN unidad_medida SET DEFAULT 'puntos porcentuales';
ALTER TABLE public.retos ALTER COLUMN unidad_medida SET NOT NULL;

DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.retos'::regclass AND conname='ck_retos_meta_cantidad_positiva') THEN
        ALTER TABLE public.retos ADD CONSTRAINT ck_retos_meta_cantidad_positiva CHECK (meta_cantidad > 0);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.retos'::regclass AND conname='ck_retos_unidad_medida') THEN
        ALTER TABLE public.retos ADD CONSTRAINT ck_retos_unidad_medida CHECK (btrim(unidad_medida) <> '');
    END IF;
END $$;

ALTER TABLE public.usuarios_retos
    ADD COLUMN IF NOT EXISTS cantidad_acumulada numeric(12,3);

DO $$ BEGIN
    IF EXISTS (SELECT 1 FROM public.usuarios_retos
               WHERE progreso IS NOT NULL AND (progreso < 0 OR progreso > 100)) THEN
        RAISE EXCEPTION 'V6 abortada: hay progreso porcentual fuera del rango 0..100; no se modificó ningún dato';
    END IF;
END $$;

UPDATE public.usuarios_retos ur
SET cantidad_acumulada = ROUND(
    r.meta_cantidad * COALESCE(ur.progreso, 0) / 100,
    3)
FROM public.retos r
WHERE r.id = ur.reto_id AND ur.cantidad_acumulada IS NULL;

ALTER TABLE public.usuarios_retos ALTER COLUMN cantidad_acumulada SET DEFAULT 0;
ALTER TABLE public.usuarios_retos ALTER COLUMN cantidad_acumulada SET NOT NULL;

DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.usuarios_retos'::regclass AND conname='ck_usuarios_retos_cantidad_no_negativa') THEN
        ALTER TABLE public.usuarios_retos ADD CONSTRAINT ck_usuarios_retos_cantidad_no_negativa CHECK (cantidad_acumulada >= 0);
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS public.avances_retos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_reto_id integer NOT NULL REFERENCES public.usuarios_retos(id),
    cantidad numeric(12,3) NOT NULL,
    registrado_en timestamp(6) without time zone NOT NULL,
    clave_solicitud uuid NOT NULL,
    CONSTRAINT ck_avances_retos_cantidad_positiva CHECK (cantidad > 0),
    CONSTRAINT uq_avances_retos_clave UNIQUE (usuario_reto_id, clave_solicitud)
);
DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.avances_retos'::regclass AND conname='ck_avances_retos_cantidad_positiva') THEN
        ALTER TABLE public.avances_retos ADD CONSTRAINT ck_avances_retos_cantidad_positiva CHECK (cantidad > 0);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.avances_retos'::regclass AND conname='uq_avances_retos_clave') THEN
        ALTER TABLE public.avances_retos ADD CONSTRAINT uq_avances_retos_clave UNIQUE (usuario_reto_id, clave_solicitud);
    END IF;
END $$;
CREATE INDEX IF NOT EXISTS ix_avances_retos_fecha
    ON public.avances_retos (usuario_reto_id, registrado_en DESC, id DESC);

-- Seis nuevos retos del catálogo. El NOT EXISTS hace segura una repetición manual;
-- la migración versionada también impide que el inicializador los inserte dos veces.
INSERT INTO public.categorias_habito (nombre, descripcion)
SELECT 'Consumo responsable', 'Hábitos de consumo con menor impacto ambiental.'
WHERE NOT EXISTS (SELECT 1 FROM public.categorias_habito
                  WHERE lower(translate(nombre, 'áéíóúÁÉÍÓÚ', 'aeiouAEIOU')) = 'consumo responsable');

INSERT INTO public.retos
    (titulo, descripcion, dificultad, puntos_recompensa, fecha_inicio, fecha_fin,
     activo, tipo, categoria_id, meta_cantidad, unidad_medida)
SELECT d.titulo, d.descripcion, d.dificultad, d.puntos, NULL,
       NULL, true, 'INDIVIDUAL', c.id, d.meta, d.unidad
FROM (VALUES
    ('Reto: muévete en bicicleta', 'Registra tres viajes realizados en bicicleta.', 'Fácil', 25, 3::numeric, 'viajes en bicicleta', 'Transporte'),
    ('Reto: duchas eficientes', 'Registra siete duchas de cinco minutos o menos.', 'Media', 25, 7::numeric, 'duchas eficientes', 'Energía'),
    ('Reto: separa tus residuos', 'Registra siete días en que separaste correctamente los residuos.', 'Fácil', 20, 7::numeric, 'días de reciclaje', 'Residuos'),
    ('Reto: menos plástico de un solo uso', 'Registra siete días evitando productos de plástico de un solo uso.', 'Media', 20, 7::numeric, 'días sin plástico de un solo uso', 'Residuos'),
    ('Reto: elige alimentos locales', 'Registra cinco días en que elegiste alimentos locales o de temporada.', 'Fácil', 15, 5::numeric, 'días con alimentos locales', 'Alimentación'),
    ('Reto: consumo responsable de papel', 'Registra siete días evitando impresiones innecesarias.', 'Fácil', 15, 7::numeric, 'días sin impresiones innecesarias', 'Consumo responsable')
) AS d(titulo, descripcion, dificultad, puntos, meta, unidad, categoria)
LEFT JOIN LATERAL (
    SELECT ch.id FROM public.categorias_habito ch
    WHERE lower(translate(ch.nombre, 'áéíóúÁÉÍÓÚ', 'aeiouAEIOU')) =
          lower(translate(d.categoria, 'áéíóúÁÉÍÓÚ', 'aeiouAEIOU'))
    ORDER BY ch.id LIMIT 1
) c ON true
WHERE NOT EXISTS (SELECT 1 FROM public.retos existing WHERE existing.titulo = d.titulo);

COMMIT;
