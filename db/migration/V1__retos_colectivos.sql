BEGIN;

ALTER TABLE public.retos ADD COLUMN IF NOT EXISTS tipo varchar(20);
UPDATE public.retos SET tipo = 'INDIVIDUAL' WHERE tipo IS NULL;
ALTER TABLE public.retos ALTER COLUMN tipo SET DEFAULT 'INDIVIDUAL';
ALTER TABLE public.retos ALTER COLUMN tipo SET NOT NULL;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint
                   WHERE conrelid = 'public.retos'::regclass AND conname = 'ck_retos_tipo') THEN
        ALTER TABLE public.retos ADD CONSTRAINT ck_retos_tipo
            CHECK (tipo IN ('INDIVIDUAL', 'COLECTIVO'));
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint
                   WHERE conrelid = 'public.retos'::regclass
                     AND conname = 'ck_retos_colectivos_fechas') THEN
        ALTER TABLE public.retos ADD CONSTRAINT ck_retos_colectivos_fechas
            CHECK (tipo <> 'COLECTIVO' OR (fecha_fin IS NOT NULL
                   AND (fecha_inicio IS NULL OR fecha_inicio <= fecha_fin)));
    END IF;
END $$;

-- Si Hibernate ya creó la tabla, CREATE TABLE no altera su definición.
-- Los ALTER y bloques siguientes completan sus restricciones sin cambiar tipos.
CREATE TABLE IF NOT EXISTS public.resultados_retos_colectivos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reto_id integer NOT NULL REFERENCES public.retos(id),
    participantes integer NOT NULL,
    progreso_final numeric(38,2) NOT NULL,
    estado varchar(255) NOT NULL,
    fecha_cierre timestamp(6) without time zone NOT NULL
);

ALTER TABLE public.resultados_retos_colectivos ALTER COLUMN reto_id SET NOT NULL;
ALTER TABLE public.resultados_retos_colectivos ALTER COLUMN participantes SET NOT NULL;
ALTER TABLE public.resultados_retos_colectivos ALTER COLUMN progreso_final SET NOT NULL;
ALTER TABLE public.resultados_retos_colectivos ALTER COLUMN estado SET NOT NULL;
ALTER TABLE public.resultados_retos_colectivos ALTER COLUMN fecha_cierre SET NOT NULL;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint c
        JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attname = 'reto_id'
        WHERE c.conrelid = 'public.resultados_retos_colectivos'::regclass
          AND c.confrelid = 'public.retos'::regclass AND c.contype = 'f'
          AND array_length(c.conkey, 1) = 1 AND c.conkey[1] = a.attnum
    ) THEN
        ALTER TABLE public.resultados_retos_colectivos
            ADD CONSTRAINT fk_resultados_retos_colectivos_reto
            FOREIGN KEY (reto_id) REFERENCES public.retos(id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint
                   WHERE conrelid = 'public.resultados_retos_colectivos'::regclass
                     AND conname = 'ck_resultados_participantes') THEN
        ALTER TABLE public.resultados_retos_colectivos
            ADD CONSTRAINT ck_resultados_participantes CHECK (participantes >= 0);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint
                   WHERE conrelid = 'public.resultados_retos_colectivos'::regclass
                     AND conname = 'ck_resultados_progreso_final') THEN
        ALTER TABLE public.resultados_retos_colectivos
            ADD CONSTRAINT ck_resultados_progreso_final
            CHECK (progreso_final BETWEEN 0 AND 100);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint
                   WHERE conrelid = 'public.resultados_retos_colectivos'::regclass
                     AND conname = 'ck_resultados_estado') THEN
        ALTER TABLE public.resultados_retos_colectivos
            ADD CONSTRAINT ck_resultados_estado
            CHECK (estado IN ('EXITOSO', 'NO_ALCANZADO'));
    END IF;
END $$;

-- Detecta índices/constraints únicos de Hibernate aunque tengan otros nombres.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_index i
        JOIN pg_attribute u ON u.attrelid = i.indrelid AND u.attname = 'usuario_id'
        JOIN pg_attribute r ON r.attrelid = i.indrelid AND r.attname = 'reto_id'
        WHERE i.indrelid = 'public.usuarios_retos'::regclass AND i.indisunique
          AND i.indisvalid AND i.indpred IS NULL AND i.indexprs IS NULL
          AND i.indnkeyatts = 2
          AND ((i.indkey[0] = u.attnum AND i.indkey[1] = r.attnum)
            OR (i.indkey[0] = r.attnum AND i.indkey[1] = u.attnum))
    ) THEN
        CREATE UNIQUE INDEX uq_usuarios_retos_usuario_reto
            ON public.usuarios_retos (usuario_id, reto_id);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_index i
        JOIN pg_attribute r ON r.attrelid = i.indrelid AND r.attname = 'reto_id'
        WHERE i.indrelid = 'public.resultados_retos_colectivos'::regclass
          AND i.indisunique AND i.indisvalid
          AND i.indpred IS NULL AND i.indexprs IS NULL
          AND i.indnkeyatts = 1 AND i.indkey[0] = r.attnum
    ) THEN
        CREATE UNIQUE INDEX uq_resultados_retos_colectivos_reto
            ON public.resultados_retos_colectivos (reto_id);
    END IF;
END $$;

