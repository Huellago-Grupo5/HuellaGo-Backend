-- HU44. Aplicación manual controlada después de V1/V2. No modifica tablas históricas.
BEGIN;

CREATE TABLE IF NOT EXISTS public.publicaciones_comunitarias (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    autor_id bigint NOT NULL,
    insignia_id integer,
    usuario_reto_id integer,
    titulo varchar(255) NOT NULL,
    fecha_publicacion timestamp(6) without time zone NOT NULL
);

ALTER TABLE public.publicaciones_comunitarias ALTER COLUMN autor_id SET NOT NULL;
ALTER TABLE public.publicaciones_comunitarias ALTER COLUMN titulo SET NOT NULL;
ALTER TABLE public.publicaciones_comunitarias ALTER COLUMN fecha_publicacion SET NOT NULL;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'public.publicaciones_comunitarias'::regclass
                   AND conname = 'fk_publicacion_autor') THEN
        ALTER TABLE public.publicaciones_comunitarias ADD CONSTRAINT fk_publicacion_autor
            FOREIGN KEY (autor_id) REFERENCES public.usuarios(id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'public.publicaciones_comunitarias'::regclass
                   AND conname = 'fk_publicacion_insignia') THEN
        ALTER TABLE public.publicaciones_comunitarias ADD CONSTRAINT fk_publicacion_insignia
            FOREIGN KEY (insignia_id) REFERENCES public.insignias(id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'public.publicaciones_comunitarias'::regclass
                   AND conname = 'fk_publicacion_participacion') THEN
        ALTER TABLE public.publicaciones_comunitarias ADD CONSTRAINT fk_publicacion_participacion
            FOREIGN KEY (usuario_reto_id) REFERENCES public.usuarios_retos(id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'public.publicaciones_comunitarias'::regclass
                   AND conname = 'ck_publicacion_origen') THEN
        ALTER TABLE public.publicaciones_comunitarias ADD CONSTRAINT ck_publicacion_origen
            CHECK (num_nonnulls(insignia_id, usuario_reto_id) = 1);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'public.publicaciones_comunitarias'::regclass
                   AND conname = 'ck_publicacion_titulo') THEN
        ALTER TABLE public.publicaciones_comunitarias ADD CONSTRAINT ck_publicacion_titulo
            CHECK (btrim(titulo) <> '');
    END IF;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS uq_publicacion_autor_insignia
    ON public.publicaciones_comunitarias (autor_id, insignia_id);
CREATE UNIQUE INDEX IF NOT EXISTS uq_publicacion_participacion
    ON public.publicaciones_comunitarias (usuario_reto_id);
CREATE INDEX IF NOT EXISTS ix_publicacion_fecha
    ON public.publicaciones_comunitarias (fecha_publicacion DESC, id DESC);

COMMIT;
